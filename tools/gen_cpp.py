"""
Transpiles the GenExpr produced by tools/dsp.py into a C++ header
(plugin/Source/MkgeeDSP.h) so the VST3/AU and the Max for Live device run the
exact same DSP.  Run:  python3 tools/gen_cpp.py
"""
import os, re
import dsp
from sim import transpile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "plugin", "Source", "MkgeeDSP.h")

UNIT = {0: "", 1: "", 2: "ms", 3: "Hz", 4: "dB", 5: "%", 7: "st"}


def main():
    code = dsp.build()
    params, hists, delays, body = transpile(code)
    pnames = list(params.keys())
    declared = set(pnames) | set(hists) | set(delays) | {"in1", "in2", "samplerate"}

    lines = []
    for b in body:
        m = re.match(r"(\w+)\.write\((.*)\)$", b)
        if m:
            lines.append(f"{b};")
            continue
        m = re.match(r"(\w+) = (.*)$", b)
        assert m, b
        name, expr = m.groups()
        if name in ("out1", "out2"):
            lines.append(f"{name}[n] = (float) ({expr});")
            continue
        if name not in declared:
            declared.add(name)
            lines.append(f"double {name} = {expr};")
        else:
            lines.append(f"{name} = {expr};")
    body_cpp = "\n            ".join(l.replace("noise()", "noise()") for l in lines)

    # parameter table
    rows = []
    for key, title, ps in dsp.SECTIONS:
        for (n, d, lo, hi, short, unit, expo, kind, enum) in ps:
            k = {"dial": 0, "toggle": 1, "tab": 2}[kind]
            e0, e1 = (enum or ["", ""])
            rows.append(f'    {{ "{n}", "{short}", "{key}", {float(d)}f, {float(lo)}f, {float(hi)}f, '
                        f'{unit}, {float(expo)}f, {k}, "{e0}", "{e1}" }},')

    hist_init = "\n        ".join(f"{h} = {v};" for h, v in hists.items())
    hist_decl = "\n    ".join(f"double {h} = {v};" for h, v in hists.items())
    delay_decl = "\n    ".join(f"DelayLine {d};" for d in delays)
    delay_init = "\n        ".join(f"{d}.init({sz});" for d, sz in delays.items())
    param_locals = "\n        ".join(f"const double {p} = P[{i}];" for i, p in enumerate(pnames))
    defaults = ", ".join(f"{params[p][0]}" for p in pnames)

    src = f"""// GENERATED by tools/gen_cpp.py from tools/dsp.py — do not edit by hand.
#pragma once
#include <cmath>
#include <cstdint>
#include <vector>
#include <algorithm>

namespace mkgee
{{
constexpr double pi = 3.14159265358979323846;
constexpr double twopi = 2.0 * pi;
inline double clamp (double x, double a, double b) {{ return x < a ? a : (x > b ? b : x); }}
inline double max (double a, double b) {{ return a > b ? a : b; }}
inline double min (double a, double b) {{ return a < b ? a : b; }}
inline double abs (double a) {{ return std::fabs (a); }}
inline double floor (double a) {{ return std::floor (a); }}
inline double pow (double a, double b) {{ return std::pow (a, b); }}
inline double exp (double a) {{ return std::exp (a); }}
inline double tan (double a) {{ return std::tan (a); }}
inline double tanh (double a) {{ return std::tanh (a); }}
inline double sin (double a) {{ return std::sin (a); }}
inline double sqrt (double a) {{ return std::sqrt (a); }}

struct DelayLine
{{
    std::vector<double> buf;
    int size = 1, w = 0;
    void init (int n) {{ size = n; buf.assign ((size_t) n, 0.0); w = 0; }}
    void clear() {{ std::fill (buf.begin(), buf.end(), 0.0); w = 0; }}
    double read (double t) const
    {{
        double pos = (double) w - t;
        double fl = std::floor (pos);
        int i = (int) fl;
        double f = pos - fl;
        i %= size; if (i < 0) i += size;
        int j = i + 1; if (j >= size) j = 0;
        return buf[(size_t) i] + (buf[(size_t) j] - buf[(size_t) i]) * f;
    }}
    void write (double x) {{ buf[(size_t) w] = x; if (++w >= size) w = 0; }}
}};

struct ParamInfo
{{
    const char* id; const char* label; const char* section;
    float def, min, max;
    int unit;      // 0 int, 1 float, 2 ms, 3 Hz, 4 dB, 5 %, 7 semitones
    float expo;    // Live-style exponent: value = min + range * x^expo
    int kind;      // 0 dial, 1 toggle, 2 two-way switch
    const char* choiceA; const char* choiceB;
}};

inline const ParamInfo kParams[] = {{
{chr(10).join(rows)}
}};
constexpr int kNumParams = {len(pnames)};

class DSP
{{
public:
    double P[kNumParams] = {{ {defaults} }};

    void prepare (double sampleRate)
    {{
        samplerate = sampleRate;
        {delay_init}
        reset();
    }}

    void reset()
    {{
        {hist_init}
        rng = 0x9E3779B9u;
    }}

    void process (const float* in1p, const float* in2p, float* out1, float* out2, int numSamples)
    {{
        {param_locals}
        for (int n = 0; n < numSamples; ++n)
        {{
            const double in1 = in1p[n];
            const double in2 = in2p[n];
            {body_cpp}
        }}
        // keep UI meters/reels fed
        tapeMotion = tp_w1;
    }}

    double tapeMotion = 0.0;

private:
    double samplerate = 48000.0;
    uint32_t rng = 0x9E3779B9u;
    double noise()
    {{
        rng ^= rng << 13; rng ^= rng >> 17; rng ^= rng << 5;
        return (double) rng * (2.0 / 4294967296.0) - 1.0;
    }}
    {hist_decl}
    {delay_decl}
}};
}} // namespace mkgee
"""
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(src)
    print("wrote", OUT, len(pnames), "params")


if __name__ == "__main__":
    main()
